"""
Bilibili session management for VietSub Studio.

- Guest session: WebView loads bilibili.com, saves cookies automatically (~720p).
- Login session: user signs in once in-app for 1080p.

NOTE: pywebview must run on the main thread (Windows).
Call prepare_bilibili_session() from UI before downloading in a background thread.
"""
from __future__ import annotations

import logging
import threading
import time
from pathlib import Path
from typing import Callable

PROJECT_ROOT = Path(__file__).resolve().parent.parent
COOKIES_DIR = PROJECT_ROOT / 'cookies'
GUEST_COOKIE_FILE = COOKIES_DIR / 'bilibili_guest.txt'
LOGIN_COOKIE_FILE = COOKIES_DIR / 'bilibili_login.txt'

GUEST_MAX_AGE_HOURS = 12
LOGIN_MAX_AGE_HOURS = 24 * 7

BILIBILI_HOME = 'https://www.bilibili.com'
BILIBILI_LOGIN = 'https://passport.bilibili.com/login'


def is_main_thread() -> bool:
    return threading.current_thread() is threading.main_thread()


def _cookie_attr(cookie, name: str, default=''):
    if isinstance(cookie, dict):
        return cookie.get(name, default)
    return getattr(cookie, name, default)


def cookies_to_netscape(cookies: list) -> str:
    lines = [
        '# Netscape HTTP Cookie File',
        '# Generated by VietSub Studio',
        '',
    ]
    now = int(time.time())
    for cookie in cookies:
        name = _cookie_attr(cookie, 'name')
        value = _cookie_attr(cookie, 'value')
        if not name:
            continue
        domain = _cookie_attr(cookie, 'domain', '.bilibili.com')
        if domain and not domain.startswith('.'):
            domain = f'.{domain}'
        path = _cookie_attr(cookie, 'path', '/') or '/'
        expires = _cookie_attr(cookie, 'expires', 0) or 0
        try:
            expires = int(expires)
        except (TypeError, ValueError):
            expires = 0
        if expires <= 0:
            expires = now + 86400 * 30
        secure = 'TRUE' if _cookie_attr(cookie, 'secure', False) else 'FALSE'
        lines.append(f'{domain}\tTRUE\t{path}\t{secure}\t{expires}\t{name}\t{value}')
    return '\n'.join(lines) + '\n'


def save_cookies_file(cookies: list, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(cookies_to_netscape(cookies), encoding='utf-8')
    logging.info('Saved Bilibili cookies: %s (%s entries)', path, len(cookies))
    return path


def _file_age_hours(path: Path) -> float:
    if not path.is_file():
        return float('inf')
    return (time.time() - path.stat().st_mtime) / 3600


def is_cookie_fresh(path: Path, max_age_hours: float) -> bool:
    return path.is_file() and _file_age_hours(path) <= max_age_hours


def has_login_session(path: Path = LOGIN_COOKIE_FILE) -> bool:
    if not path.is_file():
        return False
    text = path.read_text(encoding='utf-8', errors='ignore')
    return 'SESSDATA' in text


def get_cookie_file_for_quality(quality: str) -> Path | None:
    if quality == 'hd':
        if LOGIN_COOKIE_FILE.is_file():
            return LOGIN_COOKIE_FILE
        return None
    if GUEST_COOKIE_FILE.is_file():
        return GUEST_COOKIE_FILE
    if LOGIN_COOKIE_FILE.is_file():
        return LOGIN_COOKIE_FILE
    return None


def _filter_bilibili_cookies(cookies: list) -> list:
    return [
        c for c in cookies
        if 'bilibili' in _cookie_attr(c, 'domain', '')
    ]


def _run_guest_webview(target_url: str) -> Path | None:
    import webview

    result: dict = {'path': None}

    def on_ready(window):
        time.sleep(4)
        cookies = window.get_cookies()
        bilibili_cookies = _filter_bilibili_cookies(cookies)
        if not bilibili_cookies and cookies:
            bilibili_cookies = cookies
        if bilibili_cookies:
            result['path'] = save_cookies_file(bilibili_cookies, GUEST_COOKIE_FILE)
        else:
            logging.error(
                'Khong lay duoc cookie Bilibili tu WebView (%s cookies)',
                len(cookies),
            )
        window.destroy()

    window = webview.create_window(
        'VietSub Studio - Dang ket noi Bilibili...',
        target_url,
        width=640,
        height=480,
        hidden=True,
    )
    window.events.loaded += lambda: on_ready(window)
    webview.start(gui='edgechromium')
    return result['path']


def acquire_guest_session(video_url: str | None = None) -> Path | None:
    """Open hidden WebView on MAIN thread and save guest cookies."""
    if not is_main_thread():
        logging.warning('acquire_guest_session phai goi tu main thread')
        return get_cookie_file_for_quality('guest')
    return _run_guest_webview(video_url or BILIBILI_HOME)


def show_login_window() -> Path | None:
    """Show login WebView on MAIN thread. Save cookies when window closes."""
    if not is_main_thread():
        logging.warning('show_login_window phai goi tu main thread')
        return LOGIN_COOKIE_FILE if LOGIN_COOKIE_FILE.is_file() else None

    import webview

    result: dict = {'path': None}

    def handle_closing():
        cookies = _filter_bilibili_cookies(window.get_cookies())
        if cookies:
            result['path'] = save_cookies_file(cookies, LOGIN_COOKIE_FILE)
        return True

    window = webview.create_window(
        'Dang nhap Bilibili - dong cua so sau khi dang nhap xong',
        BILIBILI_LOGIN,
        width=960,
        height=720,
    )
    window.events.closing += handle_closing
    webview.start(gui='edgechromium')
    return result['path']


def prepare_bilibili_session(
    quality: str = 'guest',
    video_url: str | None = None,
) -> Path | None:
    """
    Prepare cookies before download. Must run on main thread (UI).

    quality:
      - 'guest': auto guest session (~720p)
      - 'hd': open login if needed (1080p)
    """
    if quality == 'hd':
        if is_cookie_fresh(LOGIN_COOKIE_FILE, LOGIN_MAX_AGE_HOURS) and has_login_session():
            return LOGIN_COOKIE_FILE
        return show_login_window()

    if is_cookie_fresh(GUEST_COOKIE_FILE, GUEST_MAX_AGE_HOURS):
        return GUEST_COOKIE_FILE
    if is_cookie_fresh(LOGIN_COOKIE_FILE, LOGIN_MAX_AGE_HOURS):
        return LOGIN_COOKIE_FILE

    return acquire_guest_session(video_url=video_url)


def ensure_bilibili_cookies(
    quality: str = 'guest',
    video_url: str | None = None,
    login_callback: Callable[[], None] | None = None,
) -> Path | None:
    """
    Used by downloader. Opens WebView only on main thread.
    From background thread: returns existing cookie file or None.
    """
    if is_main_thread():
        return prepare_bilibili_session(quality=quality, video_url=video_url)

    existing = get_cookie_file_for_quality(quality)
    if existing:
        return existing

    if login_callback and quality == 'hd':
        login_callback()
        return LOGIN_COOKIE_FILE if LOGIN_COOKIE_FILE.is_file() else None

    return None


def refresh_session_on_412(video_url: str | None = None) -> Path | None:
    for path in (GUEST_COOKIE_FILE, LOGIN_COOKIE_FILE):
        if path.is_file():
            try:
                path.unlink()
            except OSError:
                logging.warning('Could not remove old cookie file: %s', path)
    if is_main_thread():
        return acquire_guest_session(video_url=video_url)
    return None
